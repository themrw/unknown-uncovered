import soundfile as sf, json, sys
from kokoro_onnx import Kokoro
k = Kokoro('kokoro-v1.0.onnx', 'voices-v1.0.bin')
L = [
"दुनिया में युद्ध की सबसे ज़्यादा तैयारी कौन कर रहा है? आइए, पैसों के हिसाब से समझते हैं।",
"साल दो हज़ार पच्चीस में, दुनिया ने सेनाओं पर रिकॉर्ड दो दशमलव नौ ट्रिलियन डॉलर खर्च किए। ये लगातार ग्यारहवें साल की बढ़ोतरी है।",
"नंबर एक, अमेरिका। नौ सौ चौवन अरब डॉलर। ये अगले छह देशों के कुल खर्च से भी ज़्यादा है।",
"नंबर दो, चीन। तीन सौ छत्तीस अरब डॉलर। लगातार इकतीसवें साल बढ़ोतरी।",
"नंबर तीन, रूस। एक सौ नब्बे अरब डॉलर। यानी उसकी पूरी अर्थव्यवस्था का साढ़े सात प्रतिशत।",
"नंबर चार, जर्मनी। एक सौ चौदह अरब डॉलर। और अब हथियार निर्यात में दुनिया में चौथे नंबर पर।",
"नंबर पाँच, भारत। बानवे अरब डॉलर। सिर्फ़ एक साल में करीब नौ प्रतिशत की बढ़ोतरी।",
"नंबर छह, ब्रिटेन। नवासी अरब डॉलर। उन गिने-चुने देशों में से एक, जिसने खर्च घटाया।",
"नंबर सात, यूक्रेन। चौरासी अरब डॉलर। यानी उसकी अर्थव्यवस्था का लगभग चालीस प्रतिशत।",
"नंबर आठ, सऊदी अरब। तिरासी अरब डॉलर।",
"अर्थव्यवस्था के हिसाब से देखें, तो सबसे ज़्यादा बोझ यूक्रेन, अल्जीरिया, इज़राइल और रूस पर है।",
"यूरोप में चौदह प्रतिशत की बढ़ोतरी। दुनिया पहले से कहीं तेज़ी से हथियार जुटा रही है। ऐसी और जानकारी के लिए, फ़ॉलो करें।",
]
voice, speed = sys.argv[1], float(sys.argv[2])
durs = []
for i, s in enumerate(L):
    a, sr = k.create(s, voice=voice, speed=speed, lang="hi")
    sf.write(f"vo_{i:02d}.wav", a, sr); durs.append(round(len(a) / sr, 2))
json.dump(durs, open("durs.json", "w")); print(durs, sum(durs))
